// Integration test for the LOCAL hero editor and public rendering. Restores settings.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright-core');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { unlinkSync } = require('node:fs');
const bundle = `/tmp/opus-hero-config-${process.pid}.cjs`;
execFileSync('node_modules/.bin/esbuild', ['lib/hero-design.ts', '--bundle', '--platform=node', `--outfile=${bundle}`]);
const { DEFAULT_HERO_DESIGN, heroPreset } = require(bundle); unlinkSync(bundle);
const base = process.env.BASE_URL || 'http://127.0.0.1:8788';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Local test server only.');
const headers = { 'Cf-Access-Authenticated-User-Email': 'info.opuszim@gmail.com', 'Cf-Access-Jwt-Assertion': 'local-hero-test' };
(async () => {
 const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
 const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
 const original = await (await context.request.get(base + '/api/content')).json();
 const put = async design => { const r = await context.request.put(base + '/api/admin/settings', { headers, data: { hero_design: design } }); assert.equal(r.status(), 200, await r.text()); };
 const errors = [];
 try {
  const admin = await context.newPage(); admin.on('pageerror', e => errors.push(e.message));
  await admin.goto(base + '/sysadmin/');
  await admin.getByRole('button', { name: 'Home Hero Design', exact: true }).click();
  await admin.getByRole('button', { name: 'Campaign banner', exact: true }).click();
  assert.equal(await admin.getByLabel('Hero layout', { exact: true }).inputValue(), 'full_bleed');
  await admin.getByLabel('Hero layout', { exact: true }).selectOption('card');
  await admin.getByLabel('Text alignment', { exact: true }).selectOption('center');
  await admin.getByLabel('Text position', { exact: true }).selectOption('center');
  await admin.getByText('Copy, typography & buttons', { exact: true }).click();
  await admin.getByLabel('Headline override', { exact: true }).fill('Built for your next chapter.');
  await admin.getByLabel('Show headline emphasis', { exact: true }).uncheck();
  await admin.getByLabel('Fixed description override', { exact: true }).fill('Make your organisation easier to run.');
  await admin.getByRole('slider', { name: /^Desktop headline size/ }).fill('60');
  await admin.getByRole('slider', { name: /^Phone headline size/ }).fill('34');
  await admin.getByRole('slider', { name: /^Card distance from page edge/ }).fill('32');
  await admin.getByLabel('Hero corner style', { exact: true }).selectOption('uniform');
  await admin.getByRole('slider', { name: /^Card corner radius/ }).fill('40');
  await admin.getByLabel('Use reference responsive gutters').uncheck();
  await admin.getByRole('slider', { name: /^Custom edge-to-content spacing/ }).fill('56');
  await admin.getByLabel('Primary button label', { exact: true }).fill('Start a project');
  await admin.getByLabel('Primary button URL', { exact: true }).fill('/contact/?service=HeroReview');
  await admin.getByText('Background & overlay', { exact: true }).click();
  await admin.getByLabel('Static background image URL', { exact: true }).fill('/images/hero-bg.jpg');
  await admin.getByLabel('Overlay position', { exact: true }).selectOption('left');
  await admin.getByRole('slider', { name: /^Overlay width/ }).fill('80');
  await admin.getByRole('slider', { name: /^Background horizontal focal point/ }).fill('70');
  await admin.getByRole('slider', { name: /^Hero gradient angle/ }).fill('120');
  await admin.getByText('Rotation & animation', { exact: true }).click();
  await admin.getByLabel('Rotation mode', { exact: true }).selectOption('backgrounds');
  await admin.getByLabel('Transition style', { exact: true }).selectOption('slide');
  await admin.getByRole('slider', { name: /^Time per slide/ }).fill('3000');
  await admin.getByRole('slider', { name: /^Transition duration/ }).fill('400');
  await admin.getByLabel('Pause rotation while hovering the hero').uncheck();
  await admin.getByRole('button', { name: 'Add background slide', exact: true }).click();
  await admin.getByRole('button', { name: 'Add background slide', exact: true }).click();
  await admin.getByLabel('Background slide 2 URL', { exact: true }).fill('/images/hero-website-design.png');
  assert.equal(await admin.locator('.hero-editor-preview').getAttribute('data-layout'), 'card');
  assert.match(await admin.locator('.hero-editor-preview .hero-heading').innerText(), /Built for your next chapter/);
  await admin.getByRole('button', { name: 'Save hero design', exact: true }).first().click();
  await admin.getByText('Home hero design saved.', { exact: true }).waitFor();
  const saved = (await (await context.request.get(base + '/api/content')).json()).settings.hero_design;
  assert.equal(saved.heading_size, 60); assert.equal(saved.rotation, 'backgrounds'); assert.equal(saved.layout, 'card'); assert.equal(saved.backgrounds.length, 2);
  console.log('PASS: preset, live editor, copy, spacing, typography, gradient, uploads list and rotation save to D1');
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  await page.goto(base); await page.locator('.site-content[data-loading="false"]').waitFor();
  assert.equal(await page.locator('.home-hero-shell').getAttribute('data-layout'), 'card');
  assert.equal(await page.locator('.hero-heading').innerText(), 'Built for your next chapter.');
  assert.equal(await page.locator('.hero-heading').evaluate(e => getComputedStyle(e).fontSize), '60px');
  assert.equal(await page.locator('.home-hero-text').evaluate(e => getComputedStyle(e).textAlign), 'center');
  assert.equal(await page.locator('.home-hero-grid').evaluate(e => getComputedStyle(e).paddingLeft), '56px');
  assert.equal(await page.locator('.home-hero-surface').evaluate(e => getComputedStyle(e).borderRadius), '40px');
  assert.equal(await page.locator('.home-hero-overlay').getAttribute('data-placement'), 'left');
  assert.equal(await page.getByRole('link', { name: 'Start a project', exact: true }).getAttribute('href'), '/contact/?service=HeroReview');
  const message = await page.locator('.hero-description').innerText();
  await page.waitForFunction(() => document.querySelectorAll('.home-hero-background')[1]?.dataset.active === 'true', { timeout: 6000 });
  assert.equal(await page.locator('.hero-description').innerText(), message);
  assert.equal(await page.locator('.home-hero-media').count(), 0);
  await page.getByRole('button', { name: 'Pause hero rotation', exact: true }).click();
  const active = await page.locator('.home-hero-background[data-active="true"]').getAttribute('src');
  await page.waitForTimeout(3200);
  assert.equal(await page.locator('.home-hero-background[data-active="true"]').getAttribute('src'), active);
  console.log('PASS: background-only rotation keeps copy fixed; pause button, focal point, card edges and buttons work');
  for (const width of [375, 768, 1440, 1920]) { await page.setViewportSize({ width, height: 1000 }); assert.ok(await page.locator('.home-hero-copy').evaluate(e => e.getBoundingClientRect().right <= innerWidth + 1)); }
  await page.setViewportSize({ width: 375, height: 1000 });
  assert.equal(await page.locator('.hero-heading').evaluate(e => getComputedStyle(e).fontSize), '34px');
  const reduced = await browser.newPage({ reducedMotion: 'reduce' }); await reduced.goto(base); await reduced.locator('.site-content[data-loading="false"]').waitFor();
  const initial = await reduced.locator('.home-hero-background[data-active="true"]').getAttribute('src');
  await reduced.waitForTimeout(3200); assert.equal(await reduced.locator('.home-hero-background[data-active="true"]').getAttribute('src'), initial);
  assert.equal(await reduced.locator('.home-hero-background').first().evaluate(e => getComputedStyle(e).transitionDuration), '0s');
  console.log('PASS: phone/desktop sizing and reduced-motion preference');
  const split = heroPreset('classic'); split.background.background_image = '/images/hero-bg.jpg'; split.rotation = 'none'; split.show_accent = false; split.headline = 'Split with a background.';
  await put(split); await page.goto(base); await page.locator('.site-content[data-loading="false"]').waitFor();
  assert.equal(await page.locator('.home-hero-shell').getAttribute('data-media'), 'true');
  assert.equal(await page.locator('.home-hero-background').count(), 1);
  assert.equal(await page.locator('.hero-heading').innerText(), 'Split with a background.');
  assert.ok(await page.locator('.hero-media-slide[data-active="true"] img').isVisible());
  assert.deepEqual(errors, []);
  console.log('PASS: current split hero also supports a background and static foreground');
 } finally { await put(original.settings.hero_design || DEFAULT_HERO_DESIGN); await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
